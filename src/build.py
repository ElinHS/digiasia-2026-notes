    for q in n["quotes"]:
        out += ["> " + "".join(x for x in q if not x.startswith("原文："))] + ["> " + x for x in q if x.startswith("原文：")] + [""]
    if n["cases"]:
        out += ["---", "", "## 案例故事", ""]
